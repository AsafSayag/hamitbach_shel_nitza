/** ההודעה שנפתחת בוואטסאפ מכפתור האירועים. phrases = מה שהגולש סימן שהוא חוגג. */
export function eventsMessage(phrases: string[]) {
  const what =
    phrases.length === 0
      ? "יש לי אירוע בקרוב"
      : phrases.length === 1
        ? `אנחנו חוגגים ${phrases[0]}`
        : `אנחנו חוגגים ${phrases.slice(0, -1).join(", ")} ו${phrases[phrases.length - 1]}`;
  return `היי ניצה 🌸\n${what} ואשמח לשמוע על מגשי האירוח.\n\nתאריך האירוע: \nכמה אנשים: `;
}

